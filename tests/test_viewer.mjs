import assert from 'node:assert/strict';
import {TranscriptStore, turns, ordering, parseRecording} from '../tools/transcript/web/model.mjs';
const store = new TranscriptStore();
const event = (type,fields={}) => ({schema:1,type,sessionId:'test',...fields});
const s = store.apply(event('start',{clockKnown:false,bootDurable:true,bootNumber:'142',sessionNumber:'3'}));
store.apply(event('draft',{sequence:1,version:2,text:'i think'}));
store.apply(event('draft',{sequence:1,version:1,text:'stale'}));
assert.equal(s.draft.text,'i think');
const first = event('final',{sequence:1,rawText:'i think hardwareone',text:'I think HardwareOne'});
store.apply(first); store.apply(first);
assert.equal(s.phrases.size,1); assert.equal(s.draft,null);
store.apply(event('draft',{sequence:1,version:9,text:'late draft'}));
assert.equal(s.draft,null);
assert.throws(()=>store.apply({...first,text:'conflicting'}));
store.apply(event('speaker',{sequence:1,speaker:0,ready:true}));
store.apply(event('final',{sequence:2,rawText:'and i like it',text:'and I like it'}));
assert.equal(turns(s).length,2); // unknown must not inherit known speaker
store.apply(event('speaker',{sequence:2,speaker:0,ready:true}));
assert.equal(turns(s).length,1);
assert.equal(turns(s)[0].text,'I think HardwareOne and I like it');
store.apply(event('final',{sequence:3,rawText:'yes café',text:'Yes café'}));
store.apply(event('speaker',{sequence:3,speaker:1,ready:true}));
assert.equal(turns(s).length,2);
store.apply(event('end',{outcome:'done',durationMs:'134000'}));
assert.equal(s.state,'done');
assert.throws(()=>store.apply(event('speaker',{sequence:3,speaker:100,ready:true})));
const newer = {id:'new',metadata:{bootDurable:true,bootNumber:'143',sessionNumber:'1'}};
assert(ordering(newer,s)<0);
const long = {id:'long',metadata:{bootDurable:true,bootNumber:'9007199254740994',sessionNumber:'1'}};
assert(ordering(long,newer)<0);
assert.throws(()=>store.apply({schema:2}));
console.log('viewer draft/final deduplication, late labels, UTF-8, ordering and bounds passed');

const clean = JSON.stringify(event('start'))+'\n'+JSON.stringify(first)+'\n';
assert.equal(parseRecording(clean).events.length,2);
const recovered = parseRecording(clean+'{"schema":1,"type":');
assert.equal(recovered.events.length,2); assert(recovered.discardedTail);
assert.throws(()=>parseRecording(clean+'{"schema":1,\n'));
assert.throws(()=>parseRecording('{invalid}\n'+clean));
console.log('torn final-write recovery preserves complete records and rejects middle corruption');
