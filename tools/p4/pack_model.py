#!/usr/bin/env python3
"""Pack an inspected ESPDL graph for the P4 bounded local-STT loader.

Envelope: <8sIIIIII32s32s, exactly96bytes; all scalar fields little-endian.
No weights or fixture data are copied outside the supplied private directory.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import zlib

HEADER = struct.Struct('<8sIIIIII32s32s')
MAGIC = b'HW1STT1\0'
MAX_RAW_BYTES = 24*1024*1024


def digest(data): return hashlib.sha256(data).hexdigest()
def cbytes(raw): return ', '.join(f'0x{x:02x}' for x in raw)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--manifest',type=Path,required=True)
    p.add_argument('--frontend-sha256',required=True,help='SHA256 of the agreed canonical frontend contract')
    # Opt-in names so a second model (e.g. 15x5) cannot be mistaken for the deployed one.
    p.add_argument('--artifact-name',default='quartznet5x5.p4.stt')
    p.add_argument('--identity-name',default='stt_model_identity.h')
    # 'none' stores the graph uncompressed (codec 0): larger, but the firmware
    # reads it straight into place in large blocks with no inflate. Use it where
    # space is plentiful (microSD); zlib (codec 1) suits the small LittleFS.
    p.add_argument('--codec',choices=['zlib','none'],default='zlib')
    args=p.parse_args()
    if len(args.frontend_sha256)!=64:
        p.error('Frontend identity must have64 hexadecimal digits')
    try: frontend_sha=bytes.fromhex(args.frontend_sha256)
    except ValueError: p.error('Invalid frontend SHA256')
    manifest=json.loads(args.manifest.read_text()); directory=args.manifest.parent
    if manifest['stage']!='full' or manifest['frontend']!='portable' or manifest['target']!='esp32p4':
        raise ValueError('Only a full portable-frontend P4 graph is eligible')
    if manifest.get('frontend_contract_sha256') != args.frontend_sha256:
        raise ValueError('Frontend identity differs from the calibrated export manifest')
    input_=manifest['runtime']['inputs'][0]; output=manifest['runtime']['outputs'][0]
    if input_['dtype']!=3 or output['dtype']!=3 or len(input_['exponents'])!=1 or len(output['exponents'])!=1:
        raise ValueError('First runtime contract requires per-tensor int8 input/output')
    model=directory/manifest['model']['file']
    raw=model.read_bytes()
    if len(raw)!=manifest['model']['bytes'] or digest(raw)!=manifest['model']['sha256']:
        raise ValueError('Model differs from validated export manifest')
    if not 16<len(raw)<=MAX_RAW_BYTES or raw[:4]!=b'EDL2': raise ValueError('Invalid bounded ESPDL graph')
    codec_id=1 if args.codec=='zlib' else 0
    compressed=zlib.compress(raw,9) if codec_id else raw
    if codec_id and zlib.decompress(compressed)!=raw: raise ValueError('Compression roundtrip failed')
    envelope=HEADER.pack(MAGIC,1,codec_id,len(raw),len(compressed),16000,480000,
                         hashlib.sha256(raw).digest(),frontend_sha)
    assert len(envelope)==96
    if any(Path(n).name!=n or not n for n in (args.artifact_name,args.identity_name)):
        p.error('Artifact and identity names must be plain file names')
    artifact=directory/args.artifact_name
    artifact.write_bytes(envelope+compressed)
    identity=directory/args.identity_name
    identity.write_text('''// Generated by pack_model.py. Do not hand-edit model/frontend identities.
#pragma once
#include <cstddef>
#include <cstdint>
namespace hw1::stt::identity {
''' + f'''inline constexpr std::size_t kRawBytes = {len(raw)};
inline constexpr std::size_t kCompressedBytes = {len(compressed)};
inline constexpr std::uint32_t kCodec = {codec_id};  // 1 zlib, 0 stored (payload == raw)
inline constexpr std::uint8_t kRawSha[32] = {{{cbytes(hashlib.sha256(raw).digest())}}};
inline constexpr std::uint8_t kFrontendSha[32] = {{{cbytes(frontend_sha)}}};
inline constexpr char kInputName[] = {json.dumps(input_['name'])};
inline constexpr char kOutputName[] = {json.dumps(output['name'])};
inline constexpr int kInputExponent = {input_['exponents'][0]};
inline constexpr int kOutputExponent = {output['exponents'][0]};
inline constexpr int kNodeCount = {manifest['runtime']['node_count']};
inline constexpr int kSampleRate = 16000;
inline constexpr int kMaxSamples = 480000;
inline constexpr int kMaxFeatureFrames = 3000;
}} // namespace hw1::stt::identity
''')
    report={'schema':'HW1STT1','version':1,'codec':args.codec,'header_bytes':HEADER.size,
            'raw_bytes':len(raw),'compressed_bytes':len(compressed),'raw_sha256':digest(raw),
            'compressed_sha256':digest(compressed),'frontend_sha256':args.frontend_sha256,
            'artifact':{'file':artifact.name,'bytes':artifact.stat().st_size,'sha256':digest(artifact.read_bytes())},
            'identity_header':{'file':identity.name,'sha256':digest(identity.read_bytes())},
            'source_manifest_sha256':digest(args.manifest.read_bytes()),
            'packer_sha256':digest(Path(__file__).read_bytes()),'zlib_version':zlib.ZLIB_VERSION}
    (directory/'pack_manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))

if __name__=='__main__':main()
