#!/usr/bin/env python3
"""Export exact window/sparse-mel constants from the previously verified checkpoint."""
import argparse
import hashlib
import json
import math
from pathlib import Path
import numpy as np
import torch

HERE = Path(__file__).resolve().parent
PRODUCTION = HERE.parents[2] / 'components/hardwareone/stt'
WEIGHTS_SHA = '51a92f946c8cccacb723f4291be1f3285d589e5ac84fa0f6714221dbbbf333cb'
CONFIG_SHA = '1e829dd42c31d4c55d2bcf844c8abbf664ba6f1b767a9e6c8e8d26672ae5ab58'
ARCHIVE_SHA = 'd12bae27c1aa66cf69111ce3f8e56ac7aa25dac27734ea4c3315a259966a02f5'

def digest(data): return hashlib.sha256(data).hexdigest()

def load_state(directory):
    if int(torch.__version__.split('.')[0]) < 2 or (int(torch.__version__.split('.')[0]) == 2 and int(torch.__version__.split('.')[1]) < 6):
        raise ValueError('PyTorch >=2.6 required for tensor-only checkpoint loading')
    for name, wanted in [('model_weights.ckpt', WEIGHTS_SHA), ('model_config.yaml', CONFIG_SHA)]:
        if digest((directory / name).read_bytes()) != wanted:
            raise ValueError('Verified checkpoint mismatch: ' + name)
    return torch.load(directory / 'model_weights.ckpt', weights_only=True, map_location='cpu')

def generate(state):
    window = state['preprocessor.featurizer.window'].numpy()
    mel = state['preprocessor.featurizer.fb'].numpy().reshape(64, 257)
    assert window.shape == (320,) and window.dtype == mel.dtype == np.float32
    assert np.isfinite(window).all() and np.isfinite(mel).all() and (mel >= 0).all()
    starts, counts, offsets, weights = [], [], [0], []
    for row in mel:
        bins = np.flatnonzero(row)
        assert len(bins) and np.array_equal(bins, np.arange(bins[0], bins[-1] + 1))
        starts.append(int(bins[0])); counts.append(len(bins)); weights.extend(row[bins])
        offsets.append(len(weights))
    def array(name, values, kind='float'):
        def value(x): return float(x).hex() + 'f' if kind == 'float' else str(x)
        lines = [', '.join(value(x) for x in values[i:i+8]) for i in range(0,len(values),8)]
        return f'inline constexpr {kind} {name}[{len(values)}] = {{\n    ' + ',\n    '.join(lines) + '\n};\n'
    text = '// Generated by export_constants.py from the pinned NVIDIA QuartzNet5x5LS-En checkpoint.\n'
    text += '// Checkpoint weights: ' + WEIGHTS_SHA + '\n#pragma once\n#include <cstdint>\nnamespace hw1::stt::constants {\n'
    text += array('window',window)
    for name,values in [('mel_start',starts),('mel_count',counts),('mel_offset',offsets)]:
        text += array(name,values,'uint16_t')
    text += array('mel_weight',weights)
    text += array('bit_reverse',[int(f'{i:09b}'[::-1],2) for i in range(512)],'uint16_t')
    text += array('twiddle_real',np.array([math.cos(-2*math.pi*i/512) for i in range(256)],dtype=np.float32))
    text += array('twiddle_imag',np.array([math.sin(-2*math.pi*i/512) for i in range(256)],dtype=np.float32))
    text += '} // namespace hw1::stt::constants\n'
    return text, {'window_sha256_f32le':digest(window.astype('<f4').tobytes()),
                  'mel_sha256_f32le':digest(mel.astype('<f4').tobytes()), 'mel_nonzero':len(weights)}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint',type=Path,default=HERE.parents[1]/'speech_portable/private/stt-quartznet')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    content, metadata=generate(load_state(args.checkpoint))
    metadata.update({'schema':1,'checkpoint_weights_sha256':WEIGHTS_SHA,'checkpoint_config_sha256':CONFIG_SHA,
                     'archive_sha256':ARCHIVE_SHA,'model_url':'https://api.ngc.nvidia.com/v2/models/nvidia/nemospeechmodels/versions/1.0.0a5/files/QuartzNet5x5LS-En.nemo',
                     'header_sha256':digest(content.encode()),'attribution':'NVIDIA QuartzNet5x5LS-En; NGC NeMo checkpoint CC-BY-4.0 per NVIDIA maintainer clarification; see README.md'})
    outputs={'quartznet_constants.h':content,'constants-manifest.json':json.dumps(metadata,indent=2)+'\n'}
    for name,data in outputs.items():
        path=(PRODUCTION if name=='quartznet_constants.h' else HERE)/name
        if args.check:
            if path.read_text()!=data: raise ValueError('Generated constants differ: '+name)
        else: path.write_text(data)
    print(json.dumps(metadata,indent=2))
if __name__=='__main__': main()
