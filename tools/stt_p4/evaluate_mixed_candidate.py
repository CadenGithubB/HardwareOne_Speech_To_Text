#!/usr/bin/env python3
"""Host-score a locally generated selective ESP-DL export on frozen development rows.

PPQ native graphs use pickle. Only use a graph generated by your own exporter;
matching a manifest is an integrity check, not authentication of external files.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import numpy as np
import torch
from esp_ppq import TorchExecutor
from esp_ppq.api import load_native_graph
from export_quartznet import as_runtime, features, sha
from quartznet_graph import load_checkpoint, checkpoint_hashes, greedy
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'stt_train_15x5'))
from diagnostics import atomic_json,error_counts,paired_changes,summarize
sys.path.insert(0,str(HERE.parent/'stt_train/lm'))
import hw1lm


def main():
    p=argparse.ArgumentParser(description=__doc__)
    for name in ['candidate','original-export','checkpoint','stores','baseline','baseline-lm','lm','output']:
        p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--threads',type=int,default=2)
    a=p.parse_args()
    if a.output.exists():p.error('New output directory required')
    a.output.mkdir(parents=True); torch.set_num_threads(a.threads)
    def read(path):return json.loads(path.read_text())
    m=read(a.candidate/'manifest.json');orig=read(a.original_export/'manifest.json');base=read(a.baseline);base_lm=read(a.baseline_lm)
    if not m.get('precision_overrides'):raise ValueError('Expected selectively dispatched export')
    if (m['stage'], orig['stage'])!=('full','full') or m['versions']!=orig['versions']:
        raise ValueError('Full graphs with matching exporter versions required')
    def fixture_inputs(manifest):
        return [(c['fixture'],c['wav_sha256'],c['files']['features']['sha256']) for c in manifest['cases']]
    if fixture_inputs(m)!=fixture_inputs(orig):raise ValueError('Calibration fixture inputs changed')
    if m['calibration_stores']!=orig['calibration_stores'] or m['calibration_steps']!=orig['calibration_steps'] or m['unique_calibration_clips']!=orig['unique_calibration_clips']:
        raise ValueError('Original calibration clips/settings changed')
    if m.get('frontend_checkpoint',{}).get('weights_sha256')!=orig.get('frontend_checkpoint',{}).get('weights_sha256'):
        raise ValueError('Export frontend differs')
    if m['checkpoint']['weights_sha256']!=checkpoint_hashes(a.checkpoint)['weights_sha256'] or m['checkpoint']['weights_sha256']!=base['provenance']['weights_sha256']:
        raise ValueError('Checkpoint identity mismatch')
    for export,manifest in [(a.candidate,m),(a.original_export,orig)]:
        if sha(export/manifest['model']['file'])!=manifest['model']['sha256']:raise ValueError('ESPDL identity mismatch')
    if orig['model']['sha256']!=base['provenance']['espdl_sha256'] or base_lm['provenance']['espdl_sha256']!=orig['model']['sha256']:
        raise ValueError('Original baseline export mismatch')
    ng=a.candidate/'evaluation.native'
    if m['native_graph']['sha256']!=sha(ng):raise ValueError('Native graph digest mismatch')
    executor=TorchExecutor(graph=load_native_graph(str(ng)),device='cpu')
    output_meta=m['runtime']['outputs'][0]
    if output_meta['dtype']!=3:raise ValueError('This decoder requires INT8 output')
    exponent=output_meta['exponents'][0];fixture_parity=[]
    with torch.inference_mode():
        for c in m['cases']:
            f=c['files']['features']; data=np.fromfile(a.candidate/f['file'],dtype='<f4').reshape(c['runtime_input_shape']);x=torch.from_numpy(data.transpose(0,3,1,2).copy()); y=executor.forward(inputs=x)[0];raw=as_runtime(y.numpy(),dict(output_meta)).tobytes();expected=c['files']['output']
            if sha(a.candidate/f['file'])!=f['sha256'] or hashlib.sha256(raw).hexdigest()!=expected['sha256'] or raw!=(a.candidate/expected['file']).read_bytes():raise ValueError('Reloaded graph fails fixture: '+c['fixture'])
            fixture_parity.append(c['fixture'])
    config,state=load_checkpoint(a.checkpoint);vocab=config['decoder']['params']['vocabulary']
    lm=hw1lm.read_lm(a.lm);params={k:lm.params[k] for k in hw1lm.PARAM_NAMES};params['beam_width']=int(params['beam_width'])
    if lm.sha256!=base_lm['provenance']['lm_sha256'] or params!=base_lm['provenance']['decoder_params']:raise ValueError('Original decoder differs')
    rows=base['records']; indices={}; gr=[];lr=[]
    if any(r['id'].rsplit(':',1)[0]!='commonvoice-fresh-dev' for r in rows):raise ValueError('Only the frozen fresh development set may be scored')
    calibration={r['pcm_sha256'] for r in m['calibration_stores']['clips']}
    for j,r in enumerate(rows):
        name,number=r['id'].rsplit(':',1);i=int(number)
        if name not in indices:indices[name]=(read(a.stores/name/'index.json'),np.memmap(a.stores/name/'audio.bin',dtype='<i2',mode='r'))
        idx,audio=indices[name];o,n=idx['offsets'][i],idx['lengths'][i];pcm=np.array(audio[o:o+n],dtype='<i2');h=hashlib.sha256(pcm.tobytes()).hexdigest()
        if h!=r['pcm_sha256'] or h in calibration or idx['texts'][i]!=r['ref']:raise ValueError('PCM/reference identity or calibration overlap')
        with torch.inference_mode():
            x=features(pcm,None,state,'portable'); y=executor.forward(inputs=x)[0]; gh=greedy(y,vocab)
        logits=y[0,:,:,0].T.numpy();raw=np.rint(logits/(2.**exponent));q=raw.astype(np.int8)
        if not np.array_equal(q.astype(np.float32)*2.**exponent,logits):raise ValueError('Output not exactly on INT8 grid')
        lh=hw1lm.decode_int8(q,-exponent,lm,None,**params)
        for dest,hyp in [(gr,gh),(lr,lh)]:dest.append({**r,'hyp':hyp,**error_counts(r['ref'],hyp)})
        if (j+1)%4==0:atomic_json(a.output/'progress.json',{'completed':j+1,'total':len(rows)})
    result={'scope':'Real ESPDL export, host PPQ evaluation; no board timing or device parity',
        'candidate_sha256':m['model']['sha256'],'candidate_bytes':m['model']['bytes'],'precision':m['precision_overrides'],
        'original_sha256':orig['model']['sha256'],'original_bytes':orig['model']['bytes'],
        'fixture_parity':fixture_parity,'identical_calibration':True,'decoder_params':params,
        'greedy':summarize(gr),'lm':summarize(lr),'greedy_paired':paired_changes(rows,gr),'lm_paired':paired_changes(base_lm['records'],lr),
        'greedy_records':gr,'lm_records':lr,'evaluator_sha256':sha(__file__)}
    atomic_json(a.output/'results.json',result);print('Word errors: greedy',result['greedy']['errors'],'LM',result['lm']['errors'])

if __name__=='__main__':main()
